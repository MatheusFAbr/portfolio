/**
 * Regenerates src/constants/technologies.ts from the simple-icons package so the
 * SVG path data is always authentic. Run with: node scripts/generate-tech-icons.mjs
 */
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const stack = [
  ["typescript", "TypeScript", "Frontend"],
  ["react", "React", "Frontend"],
  ["nextdotjs", "Next.js", "Frontend"],
  ["tailwindcss", "Tailwind CSS", "Frontend"],
  ["nodedotjs", "Node.js", "Backend"],
  ["express", "Express", "Backend"],
  ["python", "Python", "Backend"],
  ["postgresql", "PostgreSQL", "Banco de Dados"],
  ["mysql", "MySQL", "Banco de Dados"],
  ["mongodb", "MongoDB", "Banco de Dados"],
  ["prisma", "Prisma", "Banco de Dados"],
  ["docker", "Docker", "DevOps"],
  ["git", "Git", "DevOps"],
  ["vercel", "Vercel", "DevOps"],
  ["figma", "Figma", "Design"],
];

const toKey = (slug) => "si" + slug.charAt(0).toUpperCase() + slug.slice(1);

const entries = stack.map(([slug, name, category]) => {
  const icon = icons[toKey(slug)];
  if (!icon) throw new Error(`simple-icons has no entry for "${slug}"`);
  return {
    id: slug,
    name,
    category,
    path: icon.path,
    brand: `#${icon.hex}`,
  };
});

const file = `import type { Technology } from "@/types";

// Generated by scripts/generate-tech-icons.mjs — edit the stack list there, not here.
export const technologies: Technology[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(new URL("../src/constants/technologies.ts", import.meta.url), file);
console.log(`Wrote ${entries.length} technologies.`);
